import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')

const catalogFile = path.join(rootDir, 'src/services/errors/catalog.ts')
const content = fs.readFileSync(catalogFile, 'utf8')

// Parse catalog entries simply or dynamically
const entries = []
const regex = /'([A-Z0-9-]+)':\s*\{[\s\S]*?code:\s*'([^']+)'[\s\S]*?name:\s*'([^']+)'[\s\S]*?category:\s*'([^']+)'[\s\S]*?message:\s*'([^']+)'[\s\S]*?actionableStep:\s*'([^']+)'[\s\S]*?docsAnchor:\s*'([^']+)'/g

let match
while ((match = regex.exec(content)) !== null) {
  entries.push({
    code: match[2],
    name: match[3],
    category: match[4],
    message: match[5],
    actionableStep: match[6],
    docsAnchor: match[7],
  })
}

let doc = `# Folder Error Code Catalog\n\n`
doc += `This document is auto-generated by \`scripts/gen-error-docs.mjs\` from \`src/services/errors/catalog.ts\`.\n`
doc += `It documents stable error identifiers across smart contracts, wallet integrations, IPFS, and backend services.\n\n`

const categories = [...new Set(entries.map((e) => e.category))]

for (const cat of categories) {
  doc += `## ${cat} Errors\n\n`
  const catEntries = entries.filter((e) => e.category === cat)
  for (const entry of catEntries) {
    doc += `### \`${entry.code}\` - ${entry.name} <a id="${entry.docsAnchor}"></a>\n\n`
    doc += `- **Message**: ${entry.message}\n`
    doc += `- **Actionable Step**: ${entry.actionableStep}\n`
    doc += `- **Anchor**: \`#${entry.docsAnchor}\`\n\n`
  }
}

fs.writeFileSync(path.join(rootDir, 'docs/errors.md'), doc)
console.log(`Generated docs/errors.md with ${entries.length} error entries.`)
